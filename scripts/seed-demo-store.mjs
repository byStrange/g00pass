#!/usr/bin/env node
// Seed a DEMO g00pass store (scripts/seed/demo.ts) into a directory or an
// empty GitHub repo, and print the setup values.
//
//   node scripts/seed-demo-store.mjs --out ./demo-store [--keys demo-identities.json]
//   GITHUB_TOKEN=github_pat_… node scripts/seed-demo-store.mjs --repo you/g00pass-demo-store [--branch main] [--requests you/g00pass-demo-requests]
//
// The token is read from the environment only (never from argv). It needs
// Contents: Read and write on the demo repo. DEMO ONLY: the generated private
// keys and their passphrases are written to the --keys file in clear.
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const args = Object.fromEntries(
  process.argv.slice(2).reduce((acc, a, i, all) => (a.startsWith('--') ? [...acc, [a.slice(2), all[i + 1]?.startsWith('--') ? 'true' : (all[i + 1] ?? 'true')]] : acc), []),
);
if (!args.out && !args.repo) {
  console.error('usage: --out <dir> | --repo owner/name  [--branch main] [--store-root ""] [--requests owner/name] [--keys file]');
  process.exit(2);
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const vite = await createServer({ root, configFile: false, logLevel: 'error', server: { middlewareMode: true, hmr: false }, appType: 'custom' });
try {
  const { buildDemoStore } = await vite.ssrLoadModule('/scripts/seed/demo.ts');
  const core = await vite.ssrLoadModule('/src/core/index.ts');
  const [owner, repo] = (args.repo ?? 'demo/g00pass-demo-store').split('/');
  const branch = args.branch ?? 'main';
  const storeRoot = args['store-root'] ?? '';
  const storeId = core.storeIdOf({ owner, repo, storeRoot });
  const demo = await buildDemoStore({ storeId });

  if (args.out) {
    const out = resolve(args.out);
    if (existsSync(out) && readdirSync(out).length) throw new Error(`${out} is not empty`);
    for (const [p, b] of demo.files) {
      mkdirSync(dirname(join(out, p)), { recursive: true });
      writeFileSync(join(out, p), b);
    }
    console.log(`Wrote ${demo.files.size} files to ${out} (push it to an empty private repo as-is).`);
  } else {
    const token = process.env.GITHUB_TOKEN;
    if (!token) throw new Error('set GITHUB_TOKEN (Contents: Read and write on the demo repo)');
    const client = new core.GitHubClient({ token: () => token });
    const r = { owner, repo, branch, storeRoot };
    let head = null;
    try {
      head = await core.getBranchHead(client, r);
    } catch (e) {
      if (!(e instanceof core.GitHubApiError) || ![404, 409].includes(e.status)) throw e;
    }
    if (!head) {
      // Empty repo: the Git Data API needs one commit first.
      await client.request('PUT', `/repos/${owner}/${repo}/contents/README.md`, {
        message: 'g00pass demo store',
        content: Buffer.from('# g00pass demo store\n\nDEMO ONLY. Generated by scripts/seed-demo-store.mjs.\n').toString('base64'),
        branch,
      });
      head = await core.getBranchHead(client, r);
    } else {
      const snap = await core.GitHubSnapshot.load(client, r);
      if (snap.hasFile('.gpg-id')) throw new Error('the branch already holds a store (.gpg-id); refusing to overwrite');
    }
    const changes = [...demo.files].map(([path, content]) => ({ path, content: /\.(gpg|sig)$/.test(path) ? content : new TextDecoder().decode(content) }));
    const res = await core.commitChanges(client, r, changes, { baseSha: head, message: 'g00pass: seed demo store' });
    console.log(`Committed the demo store to ${owner}/${repo}@${branch}: ${res.commitSha}`);
  }

  const keysFile = resolve(args.keys ?? 'demo-identities.json');
  writeFileSync(keysFile, JSON.stringify(demo.identities, null, 2) + '\n', { mode: 0o600 });
  const admin = demo.identities.find((i) => i.role === 'admin');
  console.log(`
Setup values (DEMO ONLY)
  Owner / Repository : ${owner} / ${repo}
  Branch             : ${branch}
  Store folder       : ${storeRoot || '(repo root)'}
  Requests repo      : ${args.requests ?? '(create a private one, e.g. ' + owner + '/g00pass-demo-requests)'}
  Global admin (pin) : ${admin.fingerprint.replace(/(.{4})(?=.)/g, '$1 ')}
  Identities         : ${keysFile} (armored private keys + passphrases; import them under "Device key")
${demo.identities.map((i) => `    ${i.role.padEnd(6)} ${i.fingerprint}  passphrase: "${i.passphrase}"`).join('\n')}
  Entries            : ${Object.keys(demo.entries).join(', ')}`);
} finally {
  await vite.close();
}
