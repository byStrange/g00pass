import { describe, expect, it } from 'vitest';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { CSP_DIRECTIVES, CSP_HEADER, CSP_META } from '../csp.config.ts';
import pkg from '../package.json';

const ROOT = join(__dirname, '..');
function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}
const srcFiles = walk(join(ROOT, 'src')).filter((f) => /\.(ts|js)$/.test(f));
const code = (f: string) =>
  readFileSync(f, 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:])\/\/.*$/gm, '$1');
const rel = (f: string) => relative(ROOT, f).replace(/\\/g, '/');

describe('trust choke-point (static guard, backs up the ESLint rule)', () => {
  it('only src/core/crypto/encrypt.ts calls openpgp encrypt or namespace-imports openpgp', () => {
    const offenders = srcFiles
      .filter((f) => rel(f) !== 'src/core/crypto/encrypt.ts')
      .filter((f) => {
        const s = code(f);
        return (
          /import\s*\*\s*as\s+\w+\s+from\s*['"]openpgp['"]/.test(s) ||
          /import\(\s*['"]openpgp['"]\s*\)/.test(s) ||
          /\bopenpgp\s*\.\s*(encrypt|encryptSessionKey)\b/.test(s) ||
          /import\s*\{[^}]*\b(encrypt|encryptSessionKey)\b[^}]*\}\s*from\s*['"]openpgp['"]/.test(s) ||
          /openpgp\s*\[\s*['"`]encrypt/.test(s) ||
          // Message#encrypt, Message.encryptSessionKey, packet.encrypt(): any `.encrypt(` call
          /\.\s*encrypt(SessionKey)?\s*\(/.test(s) ||
          /\[\s*['"`]encrypt/.test(s)
        );
      })
      .map(rel);
    expect(offenders).toEqual([]);
  });

  it('the static scan really catches Message#encrypt-style calls (self-test)', () => {
    const re = /\.\s*encrypt(SessionKey)?\s*\(/;
    expect(re.test('await message.encrypt(keys)')).toBe(true);
    expect(re.test('Message.encryptSessionKey(sk, a, b, keys)')).toBe(true);
    expect(re.test('encryptToVerified(plain, set)')).toBe(false);
  });

  it('production installs the runtime encrypt guard and asserts the lock (marker for check-dist)', () => {
    const main = code(join(ROOT, 'src/main.ts'));
    expect(main).toMatch(/lockTrustHook\(\);\s*installEncryptGuard\(\);/);
    expect(main).toContain("'g00pass: trust policy is not locked'");
    const dist = readFileSync(join(ROOT, 'scripts/check-dist.mjs'), 'utf8');
    for (const marker of ['g00pass: trust policy is not locked', 'pass-through (UNVERIFIED)', 'gpg-id signatures v1', "frame-ancestors 'none'", '_headers']) {
      expect(dist).toContain(marker);
    }
  });

  it('L2: every UI path that stores a device key validates it with inspectImportedKey first', () => {
    for (const f of ['src/ui/keyforms.ts']) {
      const s = code(join(ROOT, f));
      const calls = [...s.matchAll(/saveDeviceKey\(\s*(\w+(?:\.\w+)*)\s*\)/g)];
      for (const c of calls) {
        const before = s.slice(Math.max(0, c.index! - 200), c.index);
        const arg = c[1]!;
        const generated = /privateKeyArmored$/.test(arg); // freshly generated by generateEnrollmentKey
        expect(generated || before.includes(`inspectImportedKey(${arg})`), `${f}: saveDeviceKey(${arg})`).toBe(true);
      }
      expect(calls.length).toBeGreaterThan(0);
    }
  });

  it('production installs the signature trust hook and locks it', () => {
    const main = code(join(ROOT, 'src/main.ts'));
    expect(main).toMatch(/setTrustHook\(signatureTrustHook\);\s*lockTrustHook\(\);/);
    const trust = readFileSync(join(ROOT, 'src/core/trust.ts'), 'utf8');
    expect(trust).toContain('let installedHook: TrustHook = unconfiguredTrustHook;');
    const callers = srcFiles.filter((f) => /\bsetTrustHook\s*\(/.test(code(f)) && rel(f) !== 'src/core/trust.ts').map(rel);
    expect(callers).toEqual(['src/main.ts']);
  });

  it('encryptToVerified is the only exported encrypt and checks minted sets', () => {
    const s = readFileSync(join(ROOT, 'src/core/crypto/encrypt.ts'), 'utf8');
    expect(s).toContain('isVerifiedRecipientSet(recipients)');
  });

  it('no console logging in src (secrets must never be logged)', () => {
    const offenders = srcFiles.filter((f) => /\bconsole\s*\.\s*\w+\s*\(/.test(code(f))).map(rel);
    expect(offenders).toEqual([]);
  });

  it('tokens are never written to localStorage', () => {
    const offenders = srcFiles
      .filter((f) => /localStorage\.setItem\([^)]*token/i.test(readFileSync(f, 'utf8')))
      .map(rel);
    expect(offenders).toEqual([]);
  });
});

describe('CSP', () => {
  it('has no unsafe keywords and only api.github.com as third-party origin', () => {
    for (const csp of [CSP_META, CSP_HEADER]) {
      expect(csp).not.toMatch(/unsafe-|\*|http:|blob:|wasm/);
    }
    const origins = Object.values(CSP_DIRECTIVES)
      .flat()
      .filter((v) => /^https?:/.test(v));
    expect(origins).toEqual(['https://api.github.com']);
    expect(CSP_DIRECTIVES['script-src']).toEqual(["'self'"]);
    expect(CSP_DIRECTIVES['default-src']).toEqual(["'none'"]);
    expect(CSP_HEADER).toContain("frame-ancestors 'none'");
  });
});

describe('dependency pinning', () => {
  it('all dependencies are exact versions', () => {
    const all = { ...pkg.dependencies, ...pkg.devDependencies } as Record<string, string>;
    for (const [name, v] of Object.entries(all)) expect(v, name).toMatch(/^\d+\.\d+\.\d+$/);
  });
});
